const noteIcon = `<svg viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg"><path d="M9 18V5l12-2v13" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/><circle cx="6" cy="18" r="3" stroke="currentColor" stroke-width="1.5"/><circle cx="18" cy="16" r="3" stroke="currentColor" stroke-width="1.5"/></svg>`;

const trackList = document.getElementById('trackList');
const overlay = document.getElementById('overlay');
const overlayBackdrop = document.getElementById('overlayBackdrop');
const sheetClose = document.getElementById('sheetClose');
const sheetCover = document.getElementById('sheetCover');
const sheetTitle = document.getElementById('sheetTitle');
const sheetArtist = document.getElementById('sheetArtist');
const sheetReason = document.getElementById('sheetReason');
const sheetLyrics = document.getElementById('sheetLyrics');
const sheetAudio = document.getElementById('sheetAudio');
const sheetEyebrow = document.getElementById('sheetEyebrow');

songs.forEach((song, i) => {
  const track = document.createElement('button');
  track.className = 'track';
  track.setAttribute('type', 'button');
  track.innerHTML = `
    <span class="track-num">${String(i + 1).padStart(2, '0')}</span>
    <span class="track-thumb" style="${song.cover ? `background-image:url('${song.cover}')` : `background:linear-gradient(135deg, var(--surface-raised), var(--surface))`}">
      ${song.cover ? '' : noteIcon}
    </span>
    <span class="track-info">
      <span class="track-title">${song.title}</span>
      <span class="track-artist">${song.artist}</span>
    </span>
    <span class="track-play">
      <svg width="14" height="14" viewBox="0 0 14 14" fill="none"><path d="M3.5 2.2v9.6l8.5-4.8-8.5-4.8z" fill="currentColor"/></svg>
    </span>
  `;
  track.addEventListener('click', () => openSong(i));
  trackList.appendChild(track);
});

function openSong(i){
  const song = songs[i];
  sheetEyebrow.textContent = `track ${String(i + 1).padStart(2, '0')} of ${songs.length}`;
  sheetTitle.textContent = song.title;
  sheetArtist.textContent = song.artist;
  sheetReason.textContent = song.reason;
  sheetLyrics.textContent = song.lyrics;

  if (song.cover) {
    sheetCover.style.backgroundImage = `url('${song.cover}')`;
    sheetCover.innerHTML = '';
  } else {
    sheetCover.style.backgroundImage = 'none';
    sheetCover.style.background = 'linear-gradient(135deg, var(--surface-raised), var(--surface))';
    sheetCover.innerHTML = noteIcon;
  }

  if (song.audio) {
    sheetAudio.src = song.audio;
    sheetAudio.style.display = 'block';
    sheetAudio.play().catch(() => { /* autoplay blocked until user interacts with player — that's fine */ });
  } else {
    sheetAudio.removeAttribute('src');
    sheetAudio.style.display = 'block';
  }

  overlay.classList.add('open');
  document.body.style.overflow = 'hidden';
  sheetClose.focus();
}

function closeSong(){
  overlay.classList.remove('open');
  document.body.style.overflow = '';
  sheetAudio.pause();
}

sheetClose.addEventListener('click', closeSong);
overlayBackdrop.addEventListener('click', closeSong);
document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape' && overlay.classList.contains('open')) closeSong();
});

document.getElementById('introCta').addEventListener('click', () => {
  document.getElementById('playlist').scrollIntoView({ behavior: 'smooth' });
});
